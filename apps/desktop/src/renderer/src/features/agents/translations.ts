export type AgentTextKey = keyof typeof messages
export type AgentText = (key: AgentTextKey) => string

export function useAgentText(): AgentText {
  const { i18n } = useTranslation()
  const language = (i18n.resolvedLanguage ?? i18n.language).split('-')[0]
  const index = language === 'en' ? 1 : language === 'ja' ? 2 : 0
  return useCallback((key: AgentTextKey) => messages[key][index], [index])
}
